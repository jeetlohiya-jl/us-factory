@router.get("")
def list_material_consumption(
    search: str = Query(""), category: str = Query(""), date: str = Query(""), status_: str = Query("", alias="status"),
    page: int = Query(default=1, ge=1), page_size: int = Query(default=50, ge=1, le=200),
    db: Session = Depends(get_db), _perm=Depends(require("view")),
):
    filtered = _filtered_mc_query(db, search, category, date, status_)
    total_all = db.query(func.count(models.MaterialConsumption.id)).scalar()
    # When no filter is active, `filtered` is equivalent to the unfiltered
    # query, so matched_count == total_count by construction -- skip the
    # second COUNT round trip for the common no-filter (default list load)
    # case. Any active filter still runs its own COUNT, since the two can
    # genuinely differ.
    matched = total_all if not (search or category or date or status_) else filtered.count()
    page_ids = [
        row[0]
        for row in filtered.order_by(models.MaterialConsumption.created_at.desc())
        .offset((page - 1) * page_size)
        .limit(page_size)
        .all()
    ]
    recs_by_id = {}
    if page_ids:
        recs_by_id = {r.id: r for r in _q_for_list(db).filter(models.MaterialConsumption.id.in_(page_ids)).all()}
    items = [serialize_mc_list_item(recs_by_id[i]) for i in page_ids if i in recs_by_id]
    return {"items": items, "matched_count": matched, "total_count": total_all}


@router.post("/draft", response_model=schemas.MaterialConsumptionDetailOut, status_code=201)
def create_draft(
    db: Session = Depends(get_db),
    current_user: AuthenticatedUser = Depends(get_current_user),
    _perm=Depends(require("create")),
):
    import datetime as _dt
    mc = models.MaterialConsumption(
        consumption_date=_dt.date.today().isoformat(), status="draft", created_by=current_user.user_id,
    )
    db.add(mc)
    db.flush()
    # Every record starts with one (empty) machine slot -- Page 1 always has
    # at least one machine to fill in; "+ Add Machine" adds more.
    db.add(models.MaterialConsumptionMachineEntry(material_consumption_id=mc.id, sort_order=0))
    db.commit()
    return serialize_mc_detail(_get_or_404(db, mc.id))


