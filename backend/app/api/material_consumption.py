def get_perms(current_user: AuthenticatedUser = Depends(get_current_user), db: Session = Depends(get_db)) -> models.ModulePermission:
    perm = db.query(models.ModulePermission).filter(models.ModulePermission.user_id == current_user.user_id, models.ModulePermission.module == MODULE).first()
    if not perm:
        perm = models.ModulePermission(user_id=current_user.user_id, module=MODULE, can_view=True)
    return perm


def require(action: str):
    def _dep(perm: models.ModulePermission = Depends(get_perms)):
        if not getattr(perm, f"can_{action}", False):
            raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail=f"You do not have permission to {action} this record.")
        return perm
    return _dep


def _q(db: Session):
    return (
        db.query(models.MaterialConsumption)
        .options(
            joinedload(models.MaterialConsumption.machine_entries)
            .joinedload(models.MaterialConsumptionMachineEntry.pallets)
            .joinedload(models.MaterialConsumptionPallet.pallet),
            joinedload(models.MaterialConsumption.machine_entries)
            .joinedload(models.MaterialConsumptionMachineEntry.machine),
            joinedload(models.MaterialConsumption.production_run).joinedload(models.ProductionRun.ipqc_record),
        )
    )


def _q_for_list(db: Session):
    """Same shape as `_q()`'s eager-loaded relationships, but with the
    one-to-many collections loaded via `selectinload` (separate `IN (...)`
    queries) instead of `joinedload` (a single row-fanout join). For a page
    of ~50 parent rows this avoids the join exploding into thousands of raw
    rows that SQLAlchemy's identity map then has to collapse back down --
    the fix for finding #1 in PERF_AUDIT.md. Only ever called on an
    already-paginated id set, never on the full table."""
    return (
        db.query(models.MaterialConsumption)
        .options(
            selectinload(models.MaterialConsumption.machine_entries)
            .selectinload(models.MaterialConsumptionMachineEntry.pallets)
            .joinedload(models.MaterialConsumptionPallet.pallet),
            selectinload(models.MaterialConsumption.machine_entries)
            .joinedload(models.MaterialConsumptionMachineEntry.machine),
            joinedload(models.MaterialConsumption.production_run).joinedload(models.ProductionRun.ipqc_record),
        )
    )


def _filtered_mc_query(db: Session, search: str, category: str, date: str, status_: str):
    """Builds the WHERE clause entirely in SQL (search spans machine_entries/
    machines/pallets via correlated EXISTS subqueries generated by
    `.any()`/`.has()`) instead of the old pattern of fetching every row and
    filtering in Python."""
    q = db.query(models.MaterialConsumption.id)
    if status_:
        q = q.filter(models.MaterialConsumption.status == status_)
    if date:
        q = q.filter(models.MaterialConsumption.consumption_date == date)
    if category:
        q = q.filter(models.MaterialConsumption.machine_entries.any(models.MaterialConsumptionMachineEntry.category == category))
    if search:
        like = f"%{search.lower()}%"
        entry_matches = or_(
            func.lower(models.MaterialConsumptionMachineEntry.sku_code_snapshot).like(like),
            func.lower(models.MaterialConsumptionMachineEntry.sku_version_snapshot).like(like),
            func.lower(models.MaterialConsumptionMachineEntry.category).like(like),
            models.MaterialConsumptionMachineEntry.machine.has(func.lower(models.Machine.code).like(like)),
            models.MaterialConsumptionMachineEntry.pallets.any(
                and_(
                    models.MaterialConsumptionPallet.role == "primary",
                    models.MaterialConsumptionPallet.pallet.has(func.lower(models.Pallet.display_id).like(like)),
                )
            ),
        )
        q = q.filter(models.MaterialConsumption.machine_entries.any(entry_matches))
    return q


def _get_or_404(db: Session, mc_id: uuid.UUID) -> models.MaterialConsumption:
    mc = _q(db).filter(models.MaterialConsumption.id == mc_id).first()
    if not mc:
        raise HTTPException(status_code=404, detail="Material Consumption record not found")
    return mc


def _get_entry_or_404(mc: models.MaterialConsumption, entry_id: uuid.UUID) -> models.MaterialConsumptionMachineEntry:
    entry = next((e for e in mc.machine_entries if e.id == entry_id), None)
    if not entry:
        raise HTTPException(status_code=404, detail="Machine entry not found on this record")
    return entry


